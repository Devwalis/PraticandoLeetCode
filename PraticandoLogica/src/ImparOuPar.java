public class ImparOuPar{
	/*
	Verificar se um número inteiro é par ou impar
	
	@param number O número inteiro é par ou impar
	@return"Even" se o número for par, "Odd" se for impar.
	
	
	*/

	public String EvenOrOdd(int number){
	if(number % 2 == 0){
		return "Even";

		
} else{
	return "Odd";
	}
		
	
}

}
