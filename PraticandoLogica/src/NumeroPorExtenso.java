package PraticandoLogica.src;

public class NumeroPorExtenso {

    public static String CasoSwitch(int number){



        switch(number){
            case 0: return "Zero";
            case 1: return "Um";
            case 2: return "Two";
            case 3: return "três";
            case 4: return "Four";
            case 5: return "Cinco";
            case 6: return "six";
            case 7: return "sete";
            case 8: return "Eight";
            case 9: return "nove";


            default: return "";

        }
    }
    
}
