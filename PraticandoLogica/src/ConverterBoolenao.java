public class ConverterBoolenao{
	/*

	Converter um valor booleano para as string "yes" ou "no"

	@param bool 0 valor booleano de entrada
	@return "yes" se o valor for true, "No" se o valor for false

	*/
	public String convert(boolean bool){

	if(bool){
		return "yes";	
	}else{
		return "No";
	}


}

	}
