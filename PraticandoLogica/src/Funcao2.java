public class Funcao2{
	
	/*
	Calcular o quadrado de um número inteiro a se elevado ao quadrado
	

	@param n 0 número inteiro a se elevado ao quadrado.
	@return O quadrado do número fornecido (n multiplicado por si mesmo)

	
	*/


	public static int quadrado(int n){
	// Multiplica o número por ele mesmo para obter o quadrado.
	// A multiplicação direta é o caminho mais eficiente para potência simples.
	
	return n * n;
	
	}
	}
